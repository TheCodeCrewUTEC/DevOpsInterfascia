def sembrar(cur, texto, listado):
    cur.execute(
        """
        INSERT INTO convocatoria (
            titulo, institucion, estado, descripcion, beneficiarios, requisitos, fuente
        )
        VALUES (%s, %s, %s, %s, %s, %s, %s)
        RETURNING id
        """,
        (
            listado["nombre"],
            "Agencia Nacional de Desarrollo (ANDE)",
            listado["estado"],
            "Objetivo ya cargado para no consultar al modelo.",
            "Beneficiarios ya cargados para no consultar al modelo.",
            REQUISITOS,
            listado["link"],
        ),
    )
    convocatoria_id = cur.fetchone()[0]
    cur.execute(
        """
        INSERT INTO documento (convocatoria_id, nombre, url)
        VALUES (%s, %s, %s)
        RETURNING id
        """,
        (convocatoria_id, "ande_documento_v1.txt", listado["link"]),
    )
    documento_id = cur.fetchone()[0]
    partes = [parte.strip() for parte in texto.split("\n") if parte.strip()]
    for pagina, parte in enumerate(partes, start=1):
        cur.execute(
            """
            INSERT INTO chunk (documento_id, contenido, pagina)
            VALUES (%s, %s, %s)
            """,
            (documento_id, parte, pagina),
        )
    return convocatoria_id


def olvidar_fuente(cur, fuente):
    """Deja una sola copia de esta convocatoria al confirmar la prueba."""
    cur.execute(
        """
        DELETE FROM chunk
        WHERE documento_id IN (
            SELECT documento.id
            FROM documento
            JOIN convocatoria ON convocatoria.id = documento.convocatoria_id
            WHERE convocatoria.fuente = %s
        )
        """,
        (fuente,),
    )
    cur.execute(
        """
        DELETE FROM documento
        WHERE convocatoria_id IN (
            SELECT id FROM convocatoria WHERE fuente = %s
        )
        """,
        (fuente,),
    )
    cur.execute("DELETE FROM convocatoria WHERE fuente = %s", (fuente,))


def test_extrae_fechas_y_monto_desde_el_documento_y_los_guarda(db, extractor, monkeypatch):
    monkeypatch.setattr(
        extractor,
        "consultar_qwen",
        lambda *args, **kwargs: (_ for _ in ()).throw(
            AssertionError("la prueba no debe consultar a Qwen")
        ),
    )
    texto = FIXTURE_DOCUMENTO.read_text(encoding="utf-8")
    assert "desde el 3 de marzo de 2026 hasta el 15 de abril de 2026" in texto
    assert "$U 1.000.000" in texto
    assert "$U 8.000.000" in texto

    listado = cargar_modulo(SPIDER, "fondosspyder_listado").parsear_html_local(FIXTURE_LISTADO)[0]
    with db.cursor() as cur:
        olvidar_fuente(cur, listado["link"])
        convocatoria_id = sembrar(cur, texto, listado)
        cur.execute(
            """
            SELECT id, titulo, estado, institucion, fecha_apertura, fecha_cierre,
                   descripcion, beneficiarios, requisitos, financiamiento
            FROM convocatoria
            WHERE id = %s
            """,
            (convocatoria_id,),
        )
        fila = cur.fetchone()
        extractor.procesar_convocatoria(cur, fila)
        cur.execute(
            """
            SELECT titulo, estado, fuente, fecha_apertura, fecha_cierre,
                   financiamiento, requisitos
            FROM convocatoria
            WHERE id = %s
            """,
            (convocatoria_id,),
        )
        titulo, estado, fuente, apertura, cierre, monto, requisitos = cur.fetchone()

    assert titulo == "Despega Uruguay"
    assert estado == "Abierta"
    assert fuente == "https://ande.org.uy/convocatorias/item/despega-uruguay.html?category_id=10"
    assert apertura == APERTURA
    assert cierre == CIERRE
    assert int(monto) == MONTO_MAXIMO
    assert requisitos == REQUISITOS
    assert None not in (titulo, estado, fuente, apertura, cierre, monto, requisitos)
    db.commit()


def test_la_busqueda_de_requisitos_elige_el_texto_del_documento(db, extractor, monkeypatch):
    monkeypatch.setattr(
        extractor,
        "generar_embedding_query",
        lambda pregunta: "[" + ",".join(["0"] * extractor.EXPECTED_EMBEDDING_DIM) + "]",
    )
    texto = FIXTURE_DOCUMENTO.read_text(encoding="utf-8")
    assert REQUISITOS in texto
    listado = cargar_modulo(SPIDER, "fondosspyder_requisitos").parsear_html_local(FIXTURE_LISTADO)[0]
    with db.cursor() as cur:
        convocatoria_id = sembrar(cur, texto, listado)
        encontrados = extractor.buscar_chunks_requisitos(
            cur,
            convocatoria_id,
            extractor.CAMPOS["requisitos"]["pregunta"],
        )

    assert encontrados
    assert REQUISITOS in encontrados[0]["contenido"]
