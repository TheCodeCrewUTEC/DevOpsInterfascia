def cargar_modulo(ruta, nombre):
    spec = importlib.util.spec_from_file_location(nombre, ruta)
    modulo = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(modulo)
    return modulo


def exigir_base_de_prueba(cfg):
    if cfg["port"] == 5433 or cfg["dbname"] == "interfascia" or cfg["user"] == "interfascia":
        raise RuntimeError(
            "La prueba iba a conectarse a la base de desarrollo. "
            f"Recibido: {cfg['user']}@{cfg['host']}:{cfg['port']}/{cfg['dbname']}"
        )


def conectar():
    exigir_base_de_prueba(CONEXION_PRUEBA)
    conn = psycopg2.connect(**CONEXION_PRUEBA)
    with conn.cursor() as cur:
        cur.execute("SELECT current_database(), current_user")
        base, usuario = cur.fetchone()
    if base != "interfascia_test" or usuario != "interfascia_test":
        conn.close()
        raise RuntimeError(
            "La conexión no es la base de prueba "
            f"(base={base}, usuario={usuario})."
        )
    return conn


def asegurar_esquema(conn):
    with conn.cursor() as cur:
        cur.execute("CREATE EXTENSION IF NOT EXISTS vector")
        cur.execute(
            """
            CREATE TABLE IF NOT EXISTS convocatoria (
                id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                titulo text,
                institucion text,
                estado text,
                fecha_apertura date,
                fecha_cierre date,
                descripcion text,
                beneficiarios text,
                requisitos text,
                financiamiento text,
                creado timestamptz NOT NULL DEFAULT now(),
                fuente text
            )
            """
        )
        cur.execute(
            """
            CREATE TABLE IF NOT EXISTS documento (
                id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                convocatoria_id integer NOT NULL REFERENCES convocatoria (id),
                nombre text,
                url text,
                creado timestamptz NOT NULL DEFAULT now()
            )
            """
        )
        cur.execute(
            """
            CREATE TABLE IF NOT EXISTS chunk (
                id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                documento_id integer NOT NULL REFERENCES documento (id),
                contenido text,
                pagina integer,
                embedding vector(384),
                creado timestamptz NOT NULL DEFAULT now()
            )
            """
        )
    conn.commit()


